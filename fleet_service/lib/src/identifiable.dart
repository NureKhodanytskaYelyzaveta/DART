/// Сутність, яка вміє повідомляти власний унікальний ідентифікатор.
///
/// Клас абстрактний, а не `interface`, щоб його можна було використати як
/// обмеження `on` у домішках.
abstract class Identifiable {
  /// Створює сутність; конструктор константний, щоб нащадки могли бути
  /// константними.
  const Identifiable();

  /// Унікальний у межах типу ідентифікатор сутності.
  String get id;
}

/// Домішка, що додає службову позначку для журналу аудиту.
///
/// Обмеження `on Identifiable` дозволяє звертатися до [id] усередині домішки
/// і водночас забороняє підмішувати її до класів, які не є [Identifiable].
mixin Auditable on Identifiable {
  /// Позначка вигляду `ТипСутності#ідентифікатор`.
  String get auditTag => '$runtimeType#$id';
}
